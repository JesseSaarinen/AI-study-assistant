"""
Measure retrieval quality on the sample notes for several embedding models and
chunk sizes, and write the results as a Markdown report.

No chat API key is needed: only retrieval is evaluated. Run from the repo root:

    python scripts/evaluate_retrieval.py
    python scripts/evaluate_retrieval.py --models all-MiniLM-L6-v2 --chunk-sizes 500 1000
"""

import argparse
import sys
import tempfile
import time
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from src.embeddings import load_embedding_model  # noqa: E402
from src.evaluation import (  # noqa: E402
    QuestionResult,
    evaluate_questions,
    hit_rate,
    load_questions,
    mean_reciprocal_rank,
    threshold_tradeoff,
)
from src.ingestion import ingest_documents  # noqa: E402
from src.vector_store import get_chroma_client, get_or_create_collection  # noqa: E402

DEFAULT_MODELS = [
    "all-MiniLM-L6-v2",
    "BAAI/bge-small-en-v1.5",
    "paraphrase-multilingual-MiniLM-L12-v2",
]
DEFAULT_CHUNK_SIZES = [300, 500, 1000, 1500]
DEFAULT_THRESHOLDS = [0.3, 0.4, 0.5, 0.6, 0.7, 0.8, 1.0]
APP_DEFAULT_MODEL = "all-MiniLM-L6-v2"
APP_DEFAULT_CHUNK_SIZE = 1000


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0].strip())
    parser.add_argument("--models", nargs="+", default=DEFAULT_MODELS)
    parser.add_argument("--chunk-sizes", nargs="+", type=int, default=DEFAULT_CHUNK_SIZES)
    parser.add_argument(
        "--overlap-ratio",
        type=float,
        default=0.15,
        help="Chunk overlap as a share of chunk size (the app default is 150 / 1000).",
    )
    parser.add_argument("--top-k", type=int, default=5)
    parser.add_argument("--questions", type=Path, default=REPO_ROOT / "eval" / "questions.json")
    parser.add_argument(
        "--pdf", type=Path, default=REPO_ROOT / "sample_data" / "dsa_lecture_notes.pdf"
    )
    parser.add_argument("--output", type=Path, default=REPO_ROOT / "eval" / "results.md")
    parser.add_argument(
        "--fail-under",
        type=float,
        default=None,
        help="Exit with an error if Hit@1 for the app default configuration is below this share.",
    )

    return parser.parse_args()


def run_config(
    pdf_path: Path,
    questions,
    embedding_model,
    chunk_size: int,
    chunk_overlap: int,
    top_k: int,
    db_dir: Path,
) -> tuple[int, list[QuestionResult]]:
    client = get_chroma_client(db_dir)
    collection_name = f"eval_{chunk_size}"

    with pdf_path.open("rb") as pdf_file:
        result = ingest_documents(
            uploaded_files=[pdf_file],
            embedding_model=embedding_model,
            client=client,
            collection_name=collection_name,
            chunk_size=chunk_size,
            chunk_overlap=chunk_overlap,
            clear_existing_collection=True,
        )

    if not result.completed:
        raise RuntimeError(f"Ingestion failed: {result.stopped_reason}")

    collection = get_or_create_collection(client, collection_name)
    results = evaluate_questions(
        questions=questions,
        collection=collection,
        embedding_model=embedding_model,
        top_k=top_k,
    )

    return len(result.chunks), results


def percent(value: float) -> str:
    return f"{value * 100:.0f}%"


def build_report(args, questions, runs, thresholds_by_model, misses) -> str:
    answerable_count = sum(1 for question in questions if question.answerable)
    unanswerable_count = len(questions) - answerable_count

    lines = [
        "# Retrieval evaluation",
        "",
        "Generated by `scripts/evaluate_retrieval.py` on "
        f"`{args.pdf.relative_to(REPO_ROOT)}` with {answerable_count} answerable and "
        f"{unanswerable_count} unanswerable questions from "
        f"`{args.questions.relative_to(REPO_ROOT)}`.",
        "",
        "A retrieved chunk counts as relevant when it comes from a page that answers the "
        f"question. Top {args.top_k} chunks are retrieved per question, with chunk overlap "
        f"set to {percent(args.overlap_ratio)} of the chunk size.",
        "",
        "## Retrieval quality",
        "",
        "| Embedding model | Chunk size | Chunks | Hit@1 | Hit@3 | Hit@5 | MRR |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]

    for model_name, chunk_size, chunk_count, results in runs:
        lines.append(
            f"| `{model_name}` | {chunk_size} | {chunk_count} "
            f"| {percent(hit_rate(results, 1))} | {percent(hit_rate(results, 3))} "
            f"| {percent(hit_rate(results, 5))} | {mean_reciprocal_rank(results):.2f} |"
        )

    lines += [
        "",
        f"## Distance threshold trade-off (chunk size {APP_DEFAULT_CHUNK_SIZE})",
        "",
        "*Answerable kept* is the share of answerable questions whose relevant chunk is still "
        "retrieved after filtering. *Unanswerable rejected* is the share of unanswerable "
        "questions where every chunk is filtered out, so the app says the answer is not in "
        "the notes without calling the chat model.",
        "",
        "| Embedding model | Threshold | Answerable kept | Unanswerable rejected |",
        "|---|---:|---:|---:|",
    ]

    for model_name, rows in thresholds_by_model.items():
        for row in rows:
            lines.append(
                f"| `{model_name}` | {row.threshold:.1f} | {percent(row.answerable_kept)} "
                f"| {percent(row.unanswerable_rejected)} |"
            )

    lines += [
        "",
        f"## Misses for the app default (`{APP_DEFAULT_MODEL}`, chunk size "
        f"{APP_DEFAULT_CHUNK_SIZE})",
        "",
    ]

    if misses:
        lines += ["| Question | Expected pages | Best match rank |", "|---|---|---:|"]

        for result in misses:
            pages = ", ".join(str(page) for page in result.question.expected_pages)
            rank = result.rank if result.rank is not None else f"not in top {args.top_k}"
            lines.append(f"| {result.question.question} | {pages} | {rank} |")
    else:
        lines.append("Every answerable question had a relevant chunk at rank 1.")

    return "\n".join(lines) + "\n"


def main() -> None:
    args = parse_args()
    questions = load_questions(args.questions)
    runs = []
    thresholds_by_model = {}
    misses: list[QuestionResult] = []
    default_hit_rate: float | None = None

    with tempfile.TemporaryDirectory() as temp_dir:
        for model_name in args.models:
            started = time.perf_counter()
            embedding_model = load_embedding_model(model_name)
            print(f"Loaded {model_name} in {time.perf_counter() - started:.1f}s", flush=True)

            for chunk_size in args.chunk_sizes:
                chunk_count, results = run_config(
                    pdf_path=args.pdf,
                    questions=questions,
                    embedding_model=embedding_model,
                    chunk_size=chunk_size,
                    chunk_overlap=int(chunk_size * args.overlap_ratio),
                    top_k=args.top_k,
                    db_dir=Path(temp_dir) / model_name.replace("/", "_"),
                )
                runs.append((model_name, chunk_size, chunk_count, results))
                print(
                    f"  chunk size {chunk_size}: hit@1 {percent(hit_rate(results, 1))}, "
                    f"MRR {mean_reciprocal_rank(results):.2f}",
                    flush=True,
                )

                if chunk_size == APP_DEFAULT_CHUNK_SIZE:
                    thresholds_by_model[model_name] = threshold_tradeoff(
                        results, DEFAULT_THRESHOLDS
                    )

                    if model_name == APP_DEFAULT_MODEL:
                        default_hit_rate = hit_rate(results, 1)
                        misses = [
                            result
                            for result in results
                            if result.question.answerable and result.rank != 1
                        ]

    report = build_report(args, questions, runs, thresholds_by_model, misses)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(report, encoding="utf-8")
    print(f"\nWrote {args.output}\n")
    print(report)

    below_target = (
        args.fail_under is not None
        and default_hit_rate is not None
        and default_hit_rate < args.fail_under
    )

    if below_target:
        sys.exit(
            f"Hit@1 for the app default is {percent(default_hit_rate)}, "
            f"below the required {percent(args.fail_under)}."
        )


if __name__ == "__main__":
    main()
