"""
Measure answer quality end to end: run the labelled questions through the app's
pipeline with a real chat model, check refusals and citations against the
labels, and let a judge model grade faithfulness and relevance.

Uses the chat API settings from .env or the environment (OPENAI_API_KEY,
OPENAI_BASE_URL, OPENAI_MODEL) and the app's retrieval settings. Run from the
repo root:

    python scripts/evaluate_answers.py
    python scripts/evaluate_answers.py --limit 5 --requests-per-minute 30
"""

import argparse
import sys
import tempfile
import time
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from src.answer_evaluation import (  # noqa: E402
    AnswerEvalResult,
    PacedChatModel,
    answer_rate,
    citation_precision,
    cited_expected_page_rate,
    evaluate_answer,
    mean_faithfulness,
    mean_relevance,
    refusal_rate,
)
from src.config import get_config  # noqa: E402
from src.embeddings import load_embedding_model  # noqa: E402
from src.evaluation import load_questions  # noqa: E402
from src.ingestion import ingest_documents  # noqa: E402
from src.rag_pipeline import OpenAIChatModel  # noqa: E402
from src.vector_store import get_chroma_client, get_or_create_collection  # noqa: E402


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0].strip())
    parser.add_argument("--questions", type=Path, default=REPO_ROOT / "eval" / "questions.json")
    parser.add_argument(
        "--pdf", type=Path, default=REPO_ROOT / "sample_data" / "dsa_lecture_notes.pdf"
    )
    parser.add_argument("--output", type=Path, default=REPO_ROOT / "eval" / "answer_results.md")
    parser.add_argument(
        "--judge-model",
        default=None,
        help="Model that grades the answers. Defaults to OPENAI_MODEL.",
    )
    parser.add_argument(
        "--requests-per-minute",
        type=float,
        default=10,
        help="Upper limit on chat API requests, to stay within free tier limits.",
    )
    parser.add_argument(
        "--limit",
        type=int,
        default=None,
        help="Only evaluate the first N questions, for a quick check.",
    )

    return parser.parse_args()


def percent(value: float | None) -> str:
    return "n/a" if value is None else f"{value * 100:.0f}%"


def score(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.2f}"


def outcome(result: AnswerEvalResult) -> str:
    if result.error:
        return "error"

    if result.rejected_before_model:
        return "not found (filtered)"

    if result.refused:
        return "not found (model)"

    return "answered"


def label(value: str) -> str:
    return value.replace("_", " ")


def needs_review(result: AnswerEvalResult) -> str | None:
    """
    Return why a result deserves a closer look, or None if it looks right.
    """

    if result.error:
        return result.error

    if result.question.answerable and result.refused:
        return "Refused a question the notes answer."

    if not result.question.answerable and not result.refused:
        return "Answered a question the notes do not answer."

    if result.judgement is None:
        return None

    problems = []

    if result.judgement.faithfulness != "supported":
        problems.append(f"Faithfulness: {label(result.judgement.faithfulness)}.")

    if result.judgement.relevance != "answers":
        problems.append(f"Relevance: {label(result.judgement.relevance)}.")

    if not problems:
        return None

    if result.judgement.unsupported_claims:
        claims = "; ".join(result.judgement.unsupported_claims)
        problems.append(f"Unsupported: {claims}")
    elif result.judgement.explanation:
        problems.append(result.judgement.explanation)

    return " ".join(problems)


def table_cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def build_report(args, config, judge_model_name: str, results: list[AnswerEvalResult]) -> str:
    answerable = [result for result in results if result.question.answerable]
    unanswerable = [result for result in results if not result.question.answerable]
    rejected_early = sum(1 for result in unanswerable if result.rejected_before_model)
    threshold = (
        "disabled"
        if config.retrieval_distance_threshold is None
        else f"{config.retrieval_distance_threshold}"
    )
    judged = [result for result in results if result.judgement is not None]

    lines = [
        "# Answer evaluation",
        "",
        "Generated by `scripts/evaluate_answers.py` on "
        f"`{args.pdf.relative_to(REPO_ROOT)}` with {len(answerable)} answerable and "
        f"{len(unanswerable)} unanswerable questions from "
        f"`{args.questions.relative_to(REPO_ROOT)}`.",
        "",
        f"- Chat model: `{config.openai_model}`",
        f"- Judge model: `{judge_model_name}`",
        f"- Retrieval: `{config.embedding_model_name}`, chunk size {config.chunk_size}, "
        f"top {config.top_k}, distance threshold {threshold}",
        "",
        "## Summary",
        "",
        "| Metric | Result | What it measures |",
        "|---|---:|---|",
        f"| Answer rate | {percent(answer_rate(results))} | Answerable questions that got an "
        "answer instead of the not-found reply |",
        f"| Correct refusals | {percent(refusal_rate(results))} | Unanswerable questions that "
        f"got the not-found reply ({rejected_early} of {len(unanswerable)} filtered by distance "
        "before the chat model) |",
        f"| Cites an expected page | {percent(cited_expected_page_rate(results))} | Answered "
        "questions that cite at least one labelled page |",
        f"| Citation precision | {percent(citation_precision(results))} | Citations that point "
        "to a labelled page (a lower bound: neighbouring pages can support an answer too) |",
        f"| Faithfulness | {score(mean_faithfulness(results))} | Judge: claims are supported by "
        "the retrieved context (1 supported, 0.5 partly, 0 unsupported) |",
        f"| Relevance | {score(mean_relevance(results))} | Judge: the answer addresses the "
        "question (1 fully, 0.5 partly, 0 not) |",
        "",
        f"{len(judged)} answers were graded by the judge.",
        "",
        "## Answers to review",
        "",
    ]

    flagged = [(result, needs_review(result)) for result in results]
    flagged = [(result, reason) for result, reason in flagged if reason]

    if flagged:
        lines += ["| Question | Why |", "|---|---|"]

        for result, reason in flagged:
            lines.append(f"| {table_cell(result.question.question)} | {table_cell(reason)} |")
    else:
        lines.append("Every answer was supported, relevant and correctly refused or answered.")

    lines += [
        "",
        "## All questions",
        "",
        "| Question | Expected pages | Outcome | Cited pages | Faithfulness | Relevance |",
        "|---|---|---|---|---|---|",
    ]

    for result in results:
        expected = ", ".join(str(page) for page in result.question.expected_pages) or "none"
        cited = ", ".join(str(page) for page in result.cited_pages) or "-"
        faithfulness = label(result.judgement.faithfulness) if result.judgement else "-"
        relevance = label(result.judgement.relevance) if result.judgement else "-"
        lines.append(
            f"| {table_cell(result.question.question)} | {expected} | {outcome(result)} "
            f"| {cited} | {faithfulness} | {relevance} |"
        )

    return "\n".join(lines) + "\n"


def main() -> None:
    args = parse_args()
    config = get_config()

    if not config.openai_api_key:
        sys.exit("Set OPENAI_API_KEY in .env or the environment to run the answer evaluation.")

    judge_model_name = args.judge_model or config.openai_model
    questions = load_questions(args.questions)

    if args.limit is not None:
        questions = questions[: args.limit]

    # One paced client is shared, so answer and judge requests count against the same limit.
    chat_model = PacedChatModel(
        OpenAIChatModel(api_key=config.openai_api_key, base_url=config.openai_base_url),
        requests_per_minute=args.requests_per_minute,
    )

    started = time.perf_counter()
    embedding_model = load_embedding_model(config.embedding_model_name)
    print(f"Loaded {config.embedding_model_name} in {time.perf_counter() - started:.1f}s")

    results: list[AnswerEvalResult] = []

    with tempfile.TemporaryDirectory() as temp_dir:
        client = get_chroma_client(temp_dir)

        with args.pdf.open("rb") as pdf_file:
            ingestion = ingest_documents(
                uploaded_files=[pdf_file],
                embedding_model=embedding_model,
                client=client,
                collection_name="answer_eval",
                chunk_size=config.chunk_size,
                chunk_overlap=config.chunk_overlap,
                clear_existing_collection=True,
            )

        if not ingestion.completed:
            sys.exit(f"Ingestion failed: {ingestion.stopped_reason}")

        collection = get_or_create_collection(client, "answer_eval")

        for index, question in enumerate(questions, start=1):
            result = evaluate_answer(
                question=question,
                collection=collection,
                embedding_model=embedding_model,
                chat_model=chat_model,
                chat_model_name=config.openai_model,
                judge_model=chat_model,
                judge_model_name=judge_model_name,
                top_k=config.top_k,
                max_retrieval_distance=config.retrieval_distance_threshold,
            )
            results.append(result)

            verdict = (
                f", {result.judgement.faithfulness}, {result.judgement.relevance}"
                if result.judgement
                else ""
            )
            error = f" ({result.error})" if result.error else ""
            print(
                f"[{index}/{len(questions)}] {outcome(result)}{verdict}{error}: "
                f"{question.question}",
                flush=True,
            )

    report = build_report(args, config, judge_model_name, results)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(report, encoding="utf-8")
    print(f"\nWrote {args.output}\n")
    print(report)

    if results and all(result.error for result in results):
        sys.exit("Every question failed. Check the chat API settings.")


if __name__ == "__main__":
    main()
